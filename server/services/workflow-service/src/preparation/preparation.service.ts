import {
  BadRequestException,
  ConflictException,
  Injectable,
  NotFoundException
} from '@nestjs/common';
import { InjectRepository } from '@nestjs/typeorm';
import { anonymize } from '@offerly/helpers';
import { DataSource, EntityManager, Repository } from 'typeorm';
import { WorkflowService } from '../workflow/workflow.service';
import { WorkflowStage } from '../workflow/entities/workflow-stage.entity';
import { questionItems } from '../utils/preparation.utils';
import { QuestionAnswerItem } from './dto/preparation-content.dto';
import { GeneratePreparationDto } from './dto/preparation.dto';
import { StageQuestion } from '../workflow/entities/stage-question.entity';
import { StageCategory } from '../workflow/workflow.enums';
import {
  PAST_QUESTIONS_LIMIT,
  PAST_QUESTION_MAX_LENGTH
} from './preparation.constants';
import { PastQuestion } from './preparation.types';
import { StagePreparationData } from './entities/stage-preparation.entity';
import { AiLogService } from '@offerly/nest-common';
import { AnswerReviewerService } from './services/answer-reviewer.service';
import { PreparationContextService } from './services/preparation-context.service';
import { PreparationStrategyFactory } from './strategies/preparation-strategy.factory';
@Injectable()
export class PreparationService {
  /** Stages with an AI call in progress in this instance. */
  private readonly generating = new Set<string>();
  /** Questions with an AI answer review in progress in this instance. */
  private readonly reviewing = new Set<string>();
  constructor(
    @InjectRepository(StagePreparationData)
    private readonly preparations: Repository<StagePreparationData>,
    @InjectRepository(StageQuestion)
    private readonly questions: Repository<StageQuestion>,
    private readonly workflows: WorkflowService,
    private readonly context: PreparationContextService,
    private readonly factory: PreparationStrategyFactory,
    private readonly dataSource: DataSource,
    private readonly reviewer: AnswerReviewerService,
    private readonly aiLog: AiLogService
  ) {}
  async get(
    userId: string,
    workflowId: string,
    stageId: string
  ): Promise<StagePreparationData> {
    await this.workflows.requireStage(userId, workflowId, stageId);
    const preparation = await this.preparations.findOneBy({ stageId });
    if (!preparation)
      throw new NotFoundException('Stage preparation not found');
    return preparation;
  }

  async generate(
    userId: string,
    workflowId: string,
    stageId: string,
    input: GeneratePreparationDto,
    authorization: string
  ): Promise<StagePreparationData> {
    const stage = await this.workflows.requireStage(
      userId,
      workflowId,
      stageId,
      { workflow: true, stageType: true }
    );
    const stageType = stage.stageType;
    const instructions = input.instructions?.trim() ?? '';
    if (stageType.ownerUserId && !instructions)
      throw new BadRequestException(
        'Describe what to expect at this personal stage'
      );
    const type = this.factory.resolveType(stageType, input.type);
    if (
      this.generating.has(stageId) ||
      (await this.preparations.existsBy({ stageId }))
    )
      throw new ConflictException(
        'Preparation already exists or is being generated; delete it explicitly before regenerating'
      );
    this.generating.add(stageId);
    try {
      const [context, pastQuestions] = await Promise.all([
        this.context.load(stage.workflow.vacancyId, authorization),
        this.pastQuestions(userId, workflowId, stageId, stage.category)
      ]);
      const data = await this.aiLog.track(userId, 'preparation', () =>
        this.factory.getStrategy(type).generate({
          ...context,
          stage: {
            name: stage.name,
            category: stage.category,
            code: stageType.code
          },
          instructions:
            anonymize(instructions).text || `Prepare for ${stage.name}`,
          pastQuestions,
          language: input.language
        })
      );
      return await this.dataSource.transaction(async (manager) => {
        await this.lockStage(manager, workflowId, stageId);
        if (await manager.existsBy(StagePreparationData, { stageId }))
          throw new ConflictException(
            'Preparation was generated by another request'
          );
        return manager.save(
          StagePreparationData,
          manager.create(StagePreparationData, {
            stageId,
            data,
            instructions: instructions || null
          })
        );
      });
    } finally {
      this.generating.delete(stageId);
    }
  }

  async pastQuestions(
    userId: string,
    workflowId: string,
    stageId: string,
    category: StageCategory
  ): Promise<PastQuestion[]> {
    const questions = await this.questions
      .createQueryBuilder('question')
      .innerJoin('question.stage', 'stage')
      .innerJoin('stage.workflow', 'workflow')
      .where('workflow.userId = :userId', { userId })
      .andWhere('stage.id <> :stageId', { stageId })
      .andWhere(
        '(stage.workflowId = :workflowId OR stage.category = :category)',
        {
          workflowId,
          category
        }
      )

      .orderBy('stage.workflowId = :workflowId', 'DESC')
      .addOrderBy('question.createdAt', 'DESC')
      .limit(PAST_QUESTIONS_LIMIT)
      .select([
        'question.id',
        'question.question',
        'question.answer',
        'question.wasHard',
        'stage.id',
        'stage.name',
        'stage.category',
        'stage.workflowId'
      ])
      .getMany();

    return questions.map((item) => ({
      question: item.question.slice(0, PAST_QUESTION_MAX_LENGTH),
      answer: item.answer,
      wasHard: item.wasHard,
      stageName: item.stage.name,
      category: item.stage.category,
      sameVacancy: item.stage.workflowId === workflowId
    }));
  }

  async answer(
    userId: string,
    workflowId: string,
    stageId: string,
    questionId: string,
    userAnswer: string
  ): Promise<StagePreparationData> {
    await this.workflows.requireStage(userId, workflowId, stageId);
    return this.saveAnswer(workflowId, stageId, questionId, userAnswer);
  }

  async review(
    userId: string,
    workflowId: string,
    stageId: string,
    questionId: string,
    userAnswer: string,
    authorization: string
  ): Promise<StagePreparationData> {
    const answer = userAnswer.trim();
    if (!answer)
      throw new BadRequestException(
        'Write an answer before requesting a review'
      );
    const stage = await this.workflows.requireStage(
      userId,
      workflowId,
      stageId,
      { workflow: true }
    );
    if (this.reviewing.has(questionId))
      throw new ConflictException('This answer is already being reviewed');
    this.reviewing.add(questionId);
    try {
      const saved = await this.saveAnswer(
        workflowId,
        stageId,
        questionId,
        answer
      );
      const question = this.findQuestion(saved, questionId);
      const context = await this.context.load(
        stage.workflow.vacancyId,
        authorization
      );
      const review = await this.aiLog.track(userId, 'answer_review', () =>
        this.reviewer.review({
          ...context,
          stage: { name: stage.name, category: stage.category },
          question: question.question,
          interviewerFocus: question.tips,
          referenceAnswer: question.expectedAnswer,
          candidateAnswer: anonymize(answer).text
        })
      );
      return await this.dataSource.transaction(async (manager) => {
        await this.lockStage(manager, workflowId, stageId);
        const preparation = await manager.findOneBy(StagePreparationData, {
          stageId
        });
        if (!preparation)
          throw new NotFoundException('Stage preparation not found');
        const current = this.findQuestion(preparation, questionId);
        if (current.userAnswer !== answer)
          throw new ConflictException(
            'The answer changed while it was being reviewed'
          );
        current.feedback = { ...review, reviewedAt: new Date().toISOString() };
        return manager.save(StagePreparationData, preparation);
      });
    } finally {
      this.reviewing.delete(questionId);
    }
  }

  private saveAnswer(
    workflowId: string,
    stageId: string,
    questionId: string,
    userAnswer: string
  ): Promise<StagePreparationData> {
    return this.dataSource.transaction(async (manager) => {
      await this.lockStage(manager, workflowId, stageId);
      const preparation = await manager.findOneBy(StagePreparationData, {
        stageId
      });
      if (!preparation)
        throw new NotFoundException('Stage preparation not found');
      const question = this.findQuestion(preparation, questionId);
      if (question.userAnswer !== userAnswer) delete question.feedback;
      question.userAnswer = userAnswer;
      return manager.save(StagePreparationData, preparation);
    });
  }

  private findQuestion(
    preparation: StagePreparationData,
    questionId: string
  ): QuestionAnswerItem {
    const question = questionItems(preparation.data).find(
      (item) => item.id === questionId
    );
    if (!question)
      throw new NotFoundException('Preparation question not found');
    return question;
  }
  async remove(
    userId: string,
    workflowId: string,
    stageId: string
  ): Promise<void> {
    await this.workflows.requireStage(userId, workflowId, stageId);
    await this.dataSource.transaction(async (manager) => {
      await this.lockStage(manager, workflowId, stageId);
      const result = await manager.delete(StagePreparationData, { stageId });
      if (!result.affected)
        throw new NotFoundException('Stage preparation not found');
    });
  }
  private async lockStage(
    manager: EntityManager,
    workflowId: string,
    stageId: string
  ): Promise<void> {
    const stage = await manager.findOne(WorkflowStage, {
      where: { id: stageId, workflowId },
      lock: { mode: 'pessimistic_write' }
    });
    if (!stage) throw new NotFoundException('Workflow stage not found');
  }
}
